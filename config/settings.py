# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

def _base_depuis_url(url):
    """postgres://utilisateur:motdepasse@hote:port/base?sslmode=require  →  réglage Django.
    Utilisé en production (Neon) : une seule variable GIPAME_DB_URL au lieu de GIPAME_DB_*."""
    u = urlsplit(url)
    options = dict(parse_qsl(u.query))
    options.pop('channel_binding', None)  # ajouté par Neon dans ses URL ; inutile ici
    return {
        'ENGINE': 'django.db.backends.postgresql',
        'NAME': unquote(u.path.lstrip('/')), 'USER': unquote(u.username or ''), 'PASSWORD': unquote(u.password or ''),
        'HOST': u.hostname or '', 'PORT': str(u.port or 5432), 'OPTIONS': options,
        # Pas de connexion persistante : la base Neon peut s'endormir ; on revérifie avant réutilisation.
        'CONN_MAX_AGE': 0, 'CONN_HEALTH_CHECKS': True,
    }


